import { bindings, defineConfig, exports } from "cf/config";
import * as entrypoint from "./src/worker/index.ts" with { type: "cf-worker" };

// Your own hosted Things: the web app, the remote MCP server, and the relay to your Mac.
// Deployed with `things3pp cloud deploy`, which also uploads the setup key secret.
const name = "things3pp";

export default defineConfig({
  worker: {
    name,
    compatibilityDate: "2026-10-23",
    compatibilityFlags: ["nodejs_compat"],
    entrypoint,
    workersDev: true,
    observability: { enabled: true },
    assets: {
      notFoundHandling: "single-page-application",
      // Everything except the static web app goes to the Worker.
      runWorkerFirst: ["/api/*", "/device/*", "/mcp", "/mcp/*", "/authorize", "/token", "/register", "/.well-known/*"],
    },
    env: {
      /** OAuth clients, grants and tokens (hashed) for remote MCP. */
      /** The built web app; the Worker serves it for /authorize (consent sheet). */
      ASSETS: bindings.assets(),
      OAUTH_KV: bindings.kv(),
      /**
       * "owner": a self-hosted deployment for one person (the first Mac, proven with SETUP_KEY, owns it).
       * "open": a shared service where any Mac can create its own account (`cloud deploy --shared`).
       */
      SIGNUPS: bindings.text("owner"),
      /** Lets the first Mac claim this deployment. Generated by `things3pp cloud deploy`. */
      SETUP_KEY: bindings.secret(),
      ACCOUNT: bindings.durableObject({ worker: name, exportName: "Account" }),
      DIRECTORY: bindings.durableObject({ worker: name, exportName: "Directory" }),
    },
    exports: {
      Account: exports.durableObject({ storage: "sqlite" }),
      Directory: exports.durableObject({ storage: "sqlite" }),
    },
  },
});
